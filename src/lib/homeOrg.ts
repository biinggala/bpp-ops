/**
 * ── 누구에게나 자기 워크스페이스가 하나 ──────────────────────────────────────
 *
 * 지금까지는 **워크스페이스 없이 앱을 쓰는 상태**가 있었습니다. 그 상태 하나
 * 때문에 곳곳에 예외가 하나씩 더 있습니다 — 소속 없는 프로젝트는 어디에 서
 * 있든 늘 보이고(전환의 뜻이 흐려집니다), 전환 목록은 빌 수 있고, 설정은
 * '워크스페이스가 없습니다'를 말할 수 있습니다. 이 자리에서만 같은 부류의
 * 버그를 다섯 번 고쳤습니다: **안 온 것을 없는 것으로 읽기.**
 *
 * 그래서 노션처럼 합니다. 처음 들어온 사람에게 '○○의 워크스페이스'를 하나
 * 만들어 주고, 초대는 그 위에 얹힙니다. 상태가 하나 줄면 그 부류가 통째로
 * 줍니다.
 *
 * **이미 자리가 있는 사람에게는 아무 일도 안 일어납니다.** 회사 도메인으로
 * 들어온 사람은 이미 회사 워크스페이스에 있고, 거기에 개인 워크스페이스를
 * 하나 더 만들면 목록이 갑자기 둘이 됩니다 — 아무도 요청하지 않은 변화입니다.
 */

export interface HomeCheck {
  /** 네 곳(도메인·색인·명단·설정)이 다 대답했는가. */
  settled: boolean
  /** 색인과 도메인이 내놓은 **후보**의 수. */
  candidates: number
  /** 그중 실제로 읽어 본 곳의 수. */
  resolved: number
  /** 그중 내가 **멤버**인 곳의 수. 게스트는 안 셉니다. */
  member: number
  /** 이미 한 번 만든 적이 있는가. 계정에 적힌 표입니다. */
  madeBefore: boolean
}

/**
 * 지금 만들어야 하는가.
 *
 * 두 가지를 조심합니다.
 *
 * 1. **후보를 못 읽은 것과 후보가 없는 것.** 읽기가 실패해도 목록은 빈
 *    채로 옵니다. 그 둘을 안 가르면 네트워크가 한 번 흔들릴 때마다
 *    워크스페이스가 하나씩 늘어납니다. 그래서 `resolved === candidates`,
 *    즉 **본 것을 다 봤을 때만** 답합니다.
 * 2. **게스트는 자리가 아닙니다.** 남의 회사에 손님으로 있는 것과 내
 *    워크스페이스를 갖는 것은 다른 일이라, 게스트로만 있는 사람에게도
 *    자기 자리를 만들어 줍니다.
 */
export function needsHomeOrg(c: HomeCheck): boolean {
  if (!c.settled || c.madeBefore) return false
  if (c.resolved !== c.candidates) return false
  return c.member === 0
}

/**
 * '희건의 워크스페이스'.
 *
 * 이름을 모르면 주소의 앞부분을 씁니다 — 'heegun의 워크스페이스'. 그것도
 * 없으면 '내 워크스페이스'입니다. 어느 쪽이든 **사람이 알아보는 이름**이어야
 * 합니다: 전환 목록에서 이 줄을 자기 것으로 못 알아보면 만든 뜻이 없습니다.
 */
export function homeOrgName(displayName: string | null | undefined, email: string): string {
  const who = (displayName ?? '').trim() || (email.split('@')[0] ?? '').trim()
  return who ? `${who}의 워크스페이스` : '내 워크스페이스'
}
